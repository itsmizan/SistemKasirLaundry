    private void tblLayananMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblLayananMouseClicked
        int baris = tblLayanan.getSelectedRow();
        if (baris < 0) {
            return;
        }
        int id = (Integer) tblLayanan.getValueAt(baris, 0);
        for (Layanan l : DataStore.getDaftarLayanan()) {
            if (l.getIdLayanan() == id) {
                txtId.setText(String.valueOf(l.getIdLayanan()));
                txtNamaLayanan.setText(l.getNamaLayanan());
                txtHarga.setText(String.format("%.0f", l.getHargaPerKg()));
                txtEstimasi.setText(String.valueOf(l.getEstimasiHari()));
            }
        }
    }//GEN-LAST:event_tblLayananMouseClicked

