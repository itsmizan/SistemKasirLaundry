    private void tampilkanData() {
        DefaultTableModel model = (DefaultTableModel) tblLayanan.getModel();
        model.setRowCount(0);
        for (Layanan l : DataStore.getDaftarLayanan()) {
            model.addRow(new Object[]{l.getIdLayanan(), l.getNamaLayanan(),
                String.format("Rp %,.0f", l.getHargaPerKg()), l.getEstimasiHari() + " hari"});
        }
    }

    private void bersihkan() {
        txtId.setText(String.valueOf(DataStore.idLayananBaru()));
        txtNamaLayanan.setText("");
        txtHarga.setText("");
        txtEstimasi.setText("");
        tblLayanan.clearSelection();
        txtNamaLayanan.requestFocus();
    }

    /** Mengambil data dari form; mengembalikan null jika input tidak valid. */
    private Layanan ambilDariForm() {
        if (txtNamaLayanan.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama layanan wajib diisi!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return null;
        }
        try {
            double harga = Double.parseDouble(txtHarga.getText().trim());
            int estimasi = Integer.parseInt(txtEstimasi.getText().trim());
            return new Layanan(Integer.parseInt(txtId.getText()), txtNamaLayanan.getText().trim(), harga, estimasi);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Harga dan estimasi harus berupa angka!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return null;
        }
    }

