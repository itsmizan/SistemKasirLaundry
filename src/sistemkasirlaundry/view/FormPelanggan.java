    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        if (!validasi()) {
            return;
        }
        ambilDariForm().tambahPelanggan();
        tampilkanData(DataStore.getDaftarPelanggan());
        bersihkan();
        JOptionPane.showMessageDialog(this, "Data pelanggan berhasil ditambahkan.");
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        if (tblPelanggan.getSelectedRow() < 0) {
            JOptionPane.showMessageDialog(this, "Pilih data di tabel terlebih dahulu.");
            return;
        }
        if (!validasi()) {
            return;
        }
        ambilDariForm().ubahPelanggan();
        tampilkanData(DataStore.getDaftarPelanggan());
        bersihkan();
        JOptionPane.showMessageDialog(this, "Data pelanggan berhasil diubah.");
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        if (tblPelanggan.getSelectedRow() < 0) {
            JOptionPane.showMessageDialog(this, "Pilih data di tabel terlebih dahulu.");
            return;
        }
        int pilih = JOptionPane.showConfirmDialog(this, "Hapus pelanggan " + txtNama.getText() + "?",
                "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (pilih == JOptionPane.YES_OPTION) {
            ambilDariForm().hapusPelanggan();
            tampilkanData(DataStore.getDaftarPelanggan());
            bersihkan();
        }
    }//GEN-LAST:event_btnHapusActionPerformed

