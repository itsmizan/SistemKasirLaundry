    private void tblPelangganMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPelangganMouseClicked
        int baris = tblPelanggan.getSelectedRow();
        if (baris >= 0) {
            txtId.setText(tblPelanggan.getValueAt(baris, 0).toString());
            txtNama.setText(tblPelanggan.getValueAt(baris, 1).toString());
            txtNoHp.setText(tblPelanggan.getValueAt(baris, 2).toString());
            txtAlamat.setText(tblPelanggan.getValueAt(baris, 3).toString());
        }
    }//GEN-LAST:event_tblPelangganMouseClicked

