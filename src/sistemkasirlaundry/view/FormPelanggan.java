    private void tampilkanData(List<Pelanggan> data) {
        DefaultTableModel model = (DefaultTableModel) tblPelanggan.getModel();
        model.setRowCount(0);
        for (Pelanggan p : data) {
            model.addRow(new Object[]{p.getIdPelanggan(), p.getNama(), p.getNoHp(), p.getAlamat()});
        }
    }

    private void bersihkan() {
        txtId.setText(String.valueOf(DataStore.idPelangganBaru()));
        txtNama.setText("");
        txtNoHp.setText("");
        txtAlamat.setText("");
        tblPelanggan.clearSelection();
        txtNama.requestFocus();
    }

    private boolean validasi() {
        if (txtNama.getText().trim().isEmpty() || txtNoHp.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama dan No. HP wajib diisi!",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        return true;
    }

    private Pelanggan ambilDariForm() {
        return new Pelanggan(Integer.parseInt(txtId.getText()), txtNama.getText().trim(),
                txtNoHp.getText().trim(), txtAlamat.getText().trim());
    }

