    private void muatComboBox() {
        cmbPelanggan.removeAllItems();
        for (Pelanggan p : DataStore.getDaftarPelanggan()) {
            cmbPelanggan.addItem(p);
        }
        cmbLayanan.removeAllItems();
        for (Layanan l : DataStore.getDaftarLayanan()) {
            cmbLayanan.addItem(l);
        }
    }

    private void transaksiBaru() {
        Admin admin = DataStore.getAdminAktif();
        if (admin == null) {
            admin = DataStore.getDaftarAdmin().get(0);
        }
        transaksi = new Transaksi(DataStore.idTransaksiBaru(), admin, (Pelanggan) cmbPelanggan.getSelectedItem());
        txtNoTransaksi.setText(String.valueOf(transaksi.getIdTransaksi()));
        txtTanggal.setText(formatTanggal.format(transaksi.getTanggalMasuk()));
        txtBerat.setText("");
        cmbStatus.setSelectedIndex(0);
        tampilkanDetail();
    }

    private void tampilkanDetail() {
        DefaultTableModel model = (DefaultTableModel) tblDetail.getModel();
        model.setRowCount(0);
        for (DetailTransaksi d : transaksi.getDaftarDetail()) {
            model.addRow(new Object[]{d.getLayanan().getNamaLayanan(),
                rupiah(d.getLayanan().getHargaPerKg()), d.getBerat(), rupiah(d.getSubtotal())});
        }
        lblTotal.setText(rupiah(transaksi.hitungTotal()));
    }

    private void tampilkanRiwayat() {
        DefaultTableModel model = (DefaultTableModel) tblRiwayat.getModel();
        model.setRowCount(0);
        for (Transaksi t : DataStore.getDaftarTransaksi()) {
            model.addRow(new Object[]{t.getIdTransaksi(), formatTanggal.format(t.getTanggalMasuk()),
                formatTanggal.format(t.getTanggalSelesai()), t.getPelanggan().getNama(),
                rupiah(t.getTotalBayar()), t.getStatusBayar()});
        }
    }

    private void tampilkanNota(Transaksi t) {
        JTextArea area = new JTextArea(t.cetakNota());
        area.setFont(new java.awt.Font(java.awt.Font.MONOSPACED, java.awt.Font.PLAIN, 12));
        area.setEditable(false);
        JOptionPane.showMessageDialog(this, area, "Nota Transaksi", JOptionPane.INFORMATION_MESSAGE);
    }

    private String rupiah(double nilai) {
        return String.format("Rp %,.0f", nilai);
    }

