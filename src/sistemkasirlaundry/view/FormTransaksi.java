    private void btnTambahItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahItemActionPerformed
        Layanan layanan = (Layanan) cmbLayanan.getSelectedItem();
        if (layanan == null) {
            JOptionPane.showMessageDialog(this, "Belum ada data layanan.");
            return;
        }
        double berat;
        try {
            berat = Double.parseDouble(txtBerat.getText().trim().replace(',', '.'));
        } catch (NumberFormatException e) {
            berat = 0;
        }
        if (berat <= 0) {
            JOptionPane.showMessageDialog(this, "Berat harus berupa angka lebih dari 0.",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int idDetail = transaksi.getDaftarDetail().size() + 1;
        transaksi.tambahDetail(new DetailTransaksi(idDetail, layanan, berat));
        tampilkanDetail();
        txtBerat.setText("");
    }//GEN-LAST:event_btnTambahItemActionPerformed

    private void btnHapusItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusItemActionPerformed
        int baris = tblDetail.getSelectedRow();
        if (baris < 0) {
            JOptionPane.showMessageDialog(this, "Pilih item di tabel terlebih dahulu.");
            return;
        }
        transaksi.hapusDetail(transaksi.getDaftarDetail().get(baris));
        tampilkanDetail();
    }//GEN-LAST:event_btnHapusItemActionPerformed

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        Pelanggan pelanggan = (Pelanggan) cmbPelanggan.getSelectedItem();
        if (pelanggan == null) {
            JOptionPane.showMessageDialog(this, "Tambahkan data pelanggan terlebih dahulu.");
            return;
        }
        if (transaksi.getDaftarDetail().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Tambahkan minimal satu item layanan.");
            return;
        }
        transaksi.setPelanggan(pelanggan);
        transaksi.setStatusBayar((String) cmbStatus.getSelectedItem());
        transaksi.simpanTransaksi();
        tampilkanNota(transaksi);
        tampilkanRiwayat();
        transaksiBaru();
    }//GEN-LAST:event_btnSimpanActionPerformed

