    private void btnCetakNotaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCetakNotaActionPerformed
        int baris = tblRiwayat.getSelectedRow();
        if (baris < 0) {
            JOptionPane.showMessageDialog(this, "Pilih transaksi di tabel riwayat terlebih dahulu.");
            return;
        }
        tampilkanNota(DataStore.getDaftarTransaksi().get(baris));
    }//GEN-LAST:event_btnCetakNotaActionPerformed

